import Foundation

struct Word: Identifiable, Hashable {
    let id: Int
    let romaji: String
    let kana: String
    let script: Script
    let units: [KanaUnit]
    let categories: Set<KanaCategory>
}

/// Встроенные списки «ромадзи → кана». Категории слова вычисляются из его единиц.
/// Маленькая отдельная гласная (ぁ, ゥ…) в ромадзи пишется строчной буквой: わぁ = WAa.
enum Words {
    static let all: [Word] = {
        var list: [Word] = []
        for (raw, script) in [(hiraganaRaw, Script.hiragana), (katakanaRaw, Script.katakana)] {
            for line in raw.split(separator: "\n") {
                let parts = line.split(separator: "|", maxSplits: 1).map { $0.trimmingCharacters(in: .whitespaces) }
                guard parts.count == 2, !parts[0].isEmpty, !parts[1].isEmpty else { continue }
                let units = KanaTokenizer.units(parts[1], script: script)
                guard !units.isEmpty else { continue }
                list.append(Word(id: list.count, romaji: parts[0], kana: parts[1], script: script,
                                 units: units, categories: Set(units.map(\.category))))
            }
        }
        return list
    }()

